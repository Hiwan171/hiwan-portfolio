export type Lang = 'pt' | 'en';

/** Token de SQL: k = keyword, i = identificador, s = string, p = pontuação, t = texto. */
export type Tok = [kind: 'k' | 'i' | 's' | 'p' | 't', text: string];

type Dict = {
  text: Record<string, string>;
  query: Tok[];
  headline: { text: string; mark?: boolean }[][]; // linhas → trechos
  result: { cols: { name: string; type: string }[]; row: string[] };
  /** Seção 2. Só dados confirmados pelo Hiwan (docs/01-cases.md). */
  projects: { query: Tok[]; editorQuery: Tok[]; cols: string[]; rows: Row[] };
};

/** A mesma query de projetos, formatada em linhas para o editor do hero (ponte em tela fixa). */
const projEditorQuery = (c: string[], table: string, order: string): Tok[] => [
  ['k', 'SELECT'], ['t', ' '], ['i', c[0]], ['p', ', '], ['i', c[1]], ['p', ','], ['t', '\n       '],
  ['i', c[2]], ['p', ', '], ['i', c[3]], ['t', '\n'],
  ['k', 'FROM'], ['t', '   '], ['i', table], ['t', '\n'],
  ['k', 'ORDER BY'], ['t', ' '], ['i', order], ['t', ' '], ['k', 'DESC'], ['p', ';'],
];

export type Artifact = 'terminal' | 'queue' | 'view' | 'bi' | 'browser';

/** Uma linha de projeto + o caso completo que abre ao clicar. */
type Row = {
  name: string; area: string; stack: string; result: string;
  /** Número de impacto (só fatos confirmados em docs/01-cases.md) + legenda curta. */
  kpi: [string, string];
  artifact: Artifact;
  problem: string; solution: string; outcome: string;
};

const projQuery = (cols: string[], table: string, order: string): Tok[] => [
  ['k', 'SELECT'], ['t', ' '],
  ...cols.flatMap((c, i): Tok[] => (i ? [['p', ', '], ['i', c]] : [['i', c]])),
  ['t', ' '], ['k', 'FROM'], ['t', ' '], ['i', table],
  ['t', ' '], ['k', 'ORDER BY'], ['t', ' '], ['i', order], ['t', ' '], ['k', 'DESC'], ['p', ';'],
];

